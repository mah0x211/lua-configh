-- disable output buffering as default
local STDOUT = io.stdout
STDOUT:setvbuf('no')

-- Display name for each probe target, used in status output and macro comments.
-- These names intentionally match Autoconf conventions (e.g. "function" not "func").
local DECL_KIND = {
    headers = 'header',
    funcs = 'function',
    types = 'type',
    decls = 'decl',
    members = 'member',
    sizeof = 'sizeof',
}

--- @class configh
--- @field private __classname string  for debugging purposes
--- @field inspected table  mixed table: target hash sub-tables for dedup + integer keys for insertion-ordered flat list
--- @field exec configh.executor
--- @field output boolean
--- @field outfile file*
local Configh = {}
Configh.__index = Configh

--- __tostring returns the class name for debugging purposes
--- @return string
function Configh:__tostring()
    return self.__classname
end

--- output_status output the execution status
--- @param enabled boolean
function Configh:output_status(enabled)
    assert(type(enabled) == 'boolean', 'enabled must be boolean')
    self.output = enabled
end

--- set_stdout set the output file for status messages
--- @param outfile file*?
function Configh:set_stdout(outfile)
    assert(outfile == nil or isfile(outfile), 'outfile must be file or nil')
    self.outfile = outfile or STDOUT
end

--- printf output the message to stdout
--- @param self configh
--- @param fmt string
--- @param ... any
local function printf(self, fmt, ...)
    if not self.output then
        return
    end

    local narg = select('#', ...)
    if narg == 0 then
        -- just write the format string directly
        self.outfile:write(fmt)
        return
    end

    -- convert all non-string and non-number arguments to string to avoid format errors
    local args = {
        ...,
    }
    for i = 1, narg do
        local arg = args[i]
        if type(arg) ~= 'string' and type(arg) ~= 'number' then
            args[i] = tostring(arg)
        end
    end
    local msg = format(fmt, unpack(args, 1, narg))
    self.outfile:write(msg)
end

--- flush flush the generated definitions to the file
--- @param pathname string
--- @return boolean ok
--- @return string? err
function Configh:flush(pathname)
    assert(type(pathname) == 'string', 'pathname must be string')

    -- add a header comment
    local lines = {
        [1] = [[
/**
 * this file is generated by the lua-configh module.
 */]],
    }
    -- add features
    for _, line in ipairs(self.exec.features) do
        lines[#lines + 1] = line
        lines[#lines + 1] = ''
    end

    -- iterate inspected in insertion order; HAVE_ conversion happens here
    for _, entry in ipairs(self.inspected) do
        local macro_name = entry.name:upper():gsub('[^%w]', '_')
        if entry.target == 'sizeof' then
            lines[#lines + 1] = format('/* Size of `%s`. */', entry.name)
            lines[#lines + 1] = entry.is_exists and
                                    format('#define SIZEOF_%s %d', macro_name,
                                           entry.size) or
                                    format('/* #undef SIZEOF_%s */', macro_name)
        else
            local display =
                (entry.target == 'headers' and '<%s>' or "`%s'"):format(
                    entry.name)
            lines[#lines + 1] = format(
                                    '/* Define to 1 if you have the %s %s. */',
                                    display, DECL_KIND[entry.target])
            lines[#lines + 1] = entry.is_exists and
                                    format('#define HAVE_%s 1', macro_name) or
                                    format('/* #undef HAVE_%s */', macro_name)
            if entry.library then
                local lib_macro = entry.library:upper():gsub('[^%w]', '_')
                local lib_exists = self.inspected.libs[entry.library]
                lines[#lines + 1] = format(
                                        "/* Define to 1 if you have the `%s' library. */",
                                        entry.library)
                lines[#lines + 1] = lib_exists and
                                        format('#define HAVE_LIB_%s 1',
                                               lib_macro) or
                                        format('/* #undef HAVE_LIB_%s */',
                                               lib_macro)
            end
        end
        lines[#lines + 1] = ''
    end
    self.inspected = {
        headers = {},
        funcs = {},
        types = {},
        decls = {},
        members = {},
        sizeof = {},
        libs = {},
    }

    -- output messages
    local separator = string.rep('=', 70) .. '\n'
    printf(self, separator)
    printf(self, 'All checks are done.\n')
    printf(self, 'Writing definitions to %s ... ', pathname)
    -- write to the file
    local f, err = open(pathname, 'w+')
    if f then
        local _, cerr
        _, err = f:write(concat(lines, '\n'))
        _, cerr = f:close()
        err = err or cerr
        if err then
            remove(pathname)
        end
    end

    -- output result
    printf(self, err == nil and 'done\n' or 'failed\n')
    printf(self, separator)
    return err == nil, err
end

