local assert = assert
local concat = table.concat
local format = string.format
local gsub = string.gsub
local open = io.open
local remove = os.remove
local vformat = require('print').format
local isfile = require('io.isfile')
local executor = require('configh.executor')

-- disable output buffering as default
local STDOUT = io.stdout
STDOUT:setvbuf('no')

-- Display name for each probe target, used in status output and macro comments.
-- These names intentionally match Autoconf conventions (e.g. "function" not "func").
local DECL_KIND = {
    headers = 'header',
    funcs = 'function',
    types = 'type',
    decls = 'decl',
    members = 'member',
}

--- @class configh
--- @field inspected table  mixed table: target hash sub-tables for dedup + integer keys for insertion-ordered flat list
--- @field exec configh.executor
--- @field output boolean
--- @field outfile file*
local Configh = {}

--- new create a new configh object
--- @param cc string?
--- @return configh
function Configh:init(cc)
    self.inspected = {
        headers = {},
        funcs = {},
        types = {},
        decls = {},
        members = {},
    }
    self.exec = executor(cc)
    self.output = false
    self.outfile = STDOUT

    return self
end

--- output_status output the execution status
--- @param enabled boolean
function Configh:output_status(enabled)
    assert(type(enabled) == 'boolean', 'enabled must be boolean')
    self.output = enabled
end

--- set_stdout set the output file for status messages
--- @param outfile file*?
function Configh:set_stdout(outfile)
    assert(outfile == nil or isfile(outfile), 'outfile must be file or nil')
    self.outfile = outfile or STDOUT
end

--- printf output the message to stdout
--- @param self configh
--- @param fmt string
--- @param ... any
local function printf(self, fmt, ...)
    if self.output then
        self.outfile:write(vformat(fmt, ...))
    end
end

--- flush flush the generated definitions to the file
--- @param pathname string
--- @return boolean ok
--- @return string? err
function Configh:flush(pathname)
    assert(type(pathname) == 'string', 'pathname must be string')

    -- add a header comment
    local lines = {
        [1] = [[
/**
 * this file is generated by the lua-configh module.
 */]],
    }
    -- add features
    for _, line in ipairs(self.exec.features) do
        lines[#lines + 1] = line
        lines[#lines + 1] = ''
    end

    -- iterate inspected in insertion order; HAVE_ conversion happens here
    for _, entry in ipairs(self.inspected) do
        local fqname = (entry.target == 'headers' and '<%s>' or "`%s'"):format(
                           entry.fqname)
        local macro_name = entry.fqname:upper():gsub('[^%w]', '_')
        lines[#lines + 1] = format('/* Define to 1 if you have the %s %s. */',
                                   fqname, DECL_KIND[entry.target])
        lines[#lines + 1] = entry.is_exists and
                                format('#define HAVE_%s 1', macro_name) or
                                format('/* #undef HAVE_%s */', macro_name)
        lines[#lines + 1] = ''
    end
    self.inspected = {
        headers = {},
        funcs = {},
        types = {},
        decls = {},
        members = {},
    }

    -- output messages
    local separator = string.rep('=', 70) .. '\n'
    printf(self, separator)
    printf(self, 'All checks are done.\n')
    printf(self, 'Writing definitions to %s ... ', pathname)
    -- write to the file
    local f, err = open(pathname, 'w+')
    if f then
        local _, cerr
        _, err = f:write(concat(lines, '\n'))
        _, cerr = f:close()
        err = err or cerr
        if err then
            remove(pathname)
        end
    end

    -- output result
    printf(self, err == nil and 'done\n' or 'failed\n')
    printf(self, separator)
    return err == nil, err
end

--- set_feature set a feature macro definition
--- @param name string
--- @param value string?
function Configh:set_feature(name, value)
    self.exec:set_feature(name, value)
end

--- unset_feature unset a feature macro definition
--- @param name string
function Configh:unset_feature(name)
    self.exec:unset_feature(name)
end

--- set_cppflags set cppflags, replacing any previously set flags
--- @param flags string|string[]
function Configh:set_cppflags(flags)
    self.exec:set_cppflags(flags)
end

--- add_cppflags append cppflags to the existing list
--- @param flags string|string[]
function Configh:add_cppflags(flags)
    self.exec:add_cppflags(flags)
end

-- Maps target name to the corresponding executor method name.
local EXEC_METHOD = {
    headers = 'check_header',
    funcs = 'check_func',
    types = 'check_type',
    decls = 'check_decl',
    members = 'check_member',
}

--- check executes a probe via the EXEC_METHOD dispatch table and records
--- the result in inspected. If the fqname is already registered under
--- target, the existing entry's is_exists is updated without adding a new
--- integer-indexed slot, preventing duplicate lines in config.h output.
--- params fields:
---   headers  string|table|nil  include headers passed to the executor
---                               (for 'headers' target: the header being checked)
---   declname string             primary declaration name (header, func/type/decl name,
---                               or struct/union type name for 'members')
---   member   string?            member field name ('members' target only)
---   fqname   string?            fully qualified name used for display, hash key, and
---                               HAVE_ macro (defaults to declname; 'declname.member' for members)
--- @param self configh
--- @param target string  'headers'|'funcs'|'types'|'decls'|'members'
--- @param params table
--- @return boolean ok
--- @return string? err
local function check(self, target, params)
    assert(EXEC_METHOD[target] ~= nil,
           "target must be 'headers', 'funcs', 'types', 'decls' or 'members'")
    assert(type(params) == 'table', 'params must be table')
    assert(type(params.declname) == 'string', 'params.declname must be string')
    assert(params.headers == nil or type(params.headers) == 'string' or
               type(params.headers) == 'table',
           'params.headers must be string, table or nil')
    assert(params.member == nil or type(params.member) == 'string',
           'params.member must be string or nil')
    assert(params.fqname == nil or type(params.fqname) == 'string',
           'params.fqname must be string or nil')

    local fqname = params.fqname or params.declname

    printf(self, 'check %s: %s ... ', DECL_KIND[target], fqname)
    local ok, err = self.exec[EXEC_METHOD[target]](self.exec, params.headers,
                                                   params.declname,
                                                   params.member)
    printf(self, ok and 'found\n' or 'not found\n')
    if not ok and err then
        printf(self, '  >  ' .. gsub(err, '\n', '\n  >  '), '\n')
    end

    local entry = self.inspected[target][fqname]
    if entry then
        -- dedup: update is_exists but keep the existing integer-indexed slot
        entry.is_exists = ok
        return ok, err
    end

    local n = #self.inspected + 1
    entry = {
        target = target,
        fqname = fqname,
        declname = params.declname,
        is_exists = ok,
        order = n,
        member = params.member,
    }
    self.inspected[target][fqname] = entry
    self.inspected[n] = entry
    return ok, err
end

--- check_header check whether the header file exists
--- @param header string
--- @return boolean ok true if the header file exists
--- @return string? err error message from the compiler
function Configh:check_header(header)
    assert(type(header) == 'string', 'header must be string')
    return check(self, 'headers', {
        headers = header,
        declname = header,
    })
end

--- check_func check whether the function exists
--- @param headers string|string[]|nil
--- @param func string
--- @return boolean ok true if the function exists
--- @return string? err error message from the compiler
function Configh:check_func(headers, func)
    assert(type(func) == 'string', 'func must be string')
    return check(self, 'funcs', {
        headers = headers,
        declname = func,
    })
end

--- check_type check whether the type exists
--- @param headers string|string[]|nil
--- @param ctype string
--- @return boolean ok true if the type exists
--- @return string? err error message from the compiler
function Configh:check_type(headers, ctype)
    assert(type(ctype) == 'string', 'ctype must be string')
    return check(self, 'types', {
        headers = headers,
        declname = ctype,
    })
end

--- check_decl check whether named symbol is defined as a macro or can be used as an r-value
--- @param headers string|string[]|nil
--- @param name string
--- @return boolean ok true if the declaration exists
--- @return string? err error message from the compiler
function Configh:check_decl(headers, name)
    assert(type(name) == 'string', 'name must be string')
    return check(self, 'decls', {
        headers = headers,
        declname = name,
    })
end

--- check_member check whether the member field exists
--- @param headers string|string[]|nil
--- @param ctype string
--- @param member string
--- @return boolean ok true if the member exists
--- @return string? err error message from the compiler
function Configh:check_member(headers, ctype, member)
    assert(type(ctype) == 'string', 'ctype must be string')
    assert(type(member) == 'string', 'member must be string')
    return check(self, 'members', {
        headers = headers,
        declname = ctype,
        member = member,
        fqname = ctype .. '.' .. member,
    })
end

Configh = require('metamodule').new(Configh)
return Configh
